--changeset tracker:001-create-tracked-items
--preconditions onFail:MARK_RAN
--precondition-sql-check expectedResult:0 SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'tracked_items'
CREATE TABLE tracked_items
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT                   NOT NULL,
    url                VARCHAR(1024)            NOT NULL,
    site               VARCHAR(32)              NOT NULL,
    size_label         VARCHAR(64),
    title              VARCHAR(512)             NOT NULL,
    display_name       VARCHAR(128),
    original_price     NUMERIC(12, 2)           NOT NULL,
    discount_threshold NUMERIC(5, 2),
    is_active          BOOLEAN                  NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    last_checked_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_tracked_items_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_tracked_items_user ON tracked_items (user_id);

